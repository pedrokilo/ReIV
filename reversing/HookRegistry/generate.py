"""Generate documentation and the runtime catalog from evidence-backed entries."""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HASH = "ab21c0d90d2ca1c697785aca9dcf44635e1f8d48aa0df1d737e9190bddf0cb4c"
FIELDS = "class fn_name address reversed locked validated type rva exe_sha256 entry_kind address_checked runtime_checked reconstruction_validated standalone source evidence scope source_matches_evidence reference_names".split()


def main():
    entries = json.loads(Path(__file__).with_name("catalog.json").read_text())
    from sdk_refs import load as load_references
    revalidation_path = ROOT / "reversing/CPlayerPed/evidence/cpp-split-revalidation.json"
    revalidation = json.loads(revalidation_path.read_text(encoding="utf-8")) if revalidation_path.exists() else {}
    names_by_address, _ = load_references(ROOT)
    for row in entries:
        evidence = json.loads((ROOT / row["evidence"]).read_text(encoding="utf-8-sig"))
        assert evidence["passed"] and evidence["exe_sha256"].lower() == HASH
        row["address"] = f"0x{0x400000 + int(row['rva'],16):08X}"
        row["exe_sha256"] = HASH
        expected = evidence.get("implementation_sha256", evidence.get("wrapper_sha256"))
        if expected is None:
            expected = evidence.get("hashes", evidence.get("source_sha256", {})).get(row["source"])
        matches = hashlib.sha256((ROOT / row["source"]).read_bytes()).hexdigest() == expected
        for source, digest in evidence.get("additional_source_sha256", {}).items():
            matches = matches and hashlib.sha256((ROOT / source).read_bytes()).hexdigest() == digest
        if not matches:
            # Revalidacion tras mover cuerpos de .h a .cpp: valida solo si todos los hashes actuales coinciden.
            item = revalidation.get("items", {}).get(row["evidence"])
            matches = bool(item) and revalidation.get("passed") is True and all(
                hashlib.sha256((ROOT / path).read_bytes()).hexdigest() == digest for path, digest in item["sources"].items())
        row["source_matches_evidence"] = int(matches)
        row["reference_names"] = ";".join(names_by_address.get(row["address"].lower(), []))
    for filename, rows in (("hooks.csv", entries), ("hooks_notiv.csv", [])):
        with (ROOT / "docs" / filename).open("w", encoding="utf-8", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=FIELDS)
            writer.writeheader(); writer.writerows(rows)
    header = ["#pragma once", "// Generated by reversing/HookRegistry/generate.py; edit catalog.json instead.", "namespace reiv::debug {", "struct CatalogEntry { const char* owner; const char* function; unsigned rva; bool reversed; bool validated; const char* kind; const char* evidence; };", "inline constexpr CatalogEntry catalog[] = {"]
    for e in entries:
        header.append("    {" + ", ".join([json.dumps(e["class"]),json.dumps(e["fn_name"]),e["rva"]+"u",str(bool(e["reversed"])).lower(),str(bool(e["validated"])).lower(),json.dumps(e["entry_kind"]),json.dumps(e["evidence"])]) + "},")
    header += ["};", "}", ""]
    (ROOT / "source/core/HooksCatalog.h").write_text("\n".join(header), encoding="utf-8")
    print(f"Generated {len(entries)} evidence-backed entries, runtime catalog; ReversedClasses.md y la clasificacion por procedencia los genera tools/ReIV.Tools (C#)")
    from correlate_classes import main as correlate
    correlate()


if __name__ == "__main__": main()
